// Records host/duration-format-cases.js in Node 24+: the expected outputs of the test262 DurationFormat
// tests built on Intl.NumberFormat, which Hermes's own cannot run on Apple platforms (no
// formatToParts, no roundingMode, no microsecond or nanosecond unit). Expectations come from the
// harness's spec implementation on V8's NumberFormat, not from V8's DurationFormat.
//   node host/duration-format-golden.mjs vendor/test262 <test files...>
// host/duration-format.js checks them: hi-host host/duration-format-cases.js host/duration-format.js
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import vm from 'node:vm';

const [root, ...files] = process.argv.slice(2);
const harness = ['assert.js', 'sta.js', 'testIntl.js', 'compareArray.js'].map((h) => readFileSync(join(root, 'harness', h), 'utf8')).join('\n');
const cases = [];
let failed = 0; // tests that throw for another reason than an assertion
for (const file of files) {
  const context = vm.createContext({ print: () => {} });
  vm.runInContext(harness, context);
  // Expectations come from the harness, so V8's own results need not pass: keep every case.
  vm.runInContext('assert.sameValue = function () {}; assert.compareArray = function () {};', context);
  // Every call made through Intl.DurationFormat, with what V8 returns.
  context.__record = (locales, options, method, duration, output) =>
    cases.push({ locales, options, method, duration, output });
  vm.runInContext(`(function () {
    var DF = Intl.DurationFormat;
    var proto = DF.prototype;
    var format = proto.format, formatToParts = proto.formatToParts;
    var args = new WeakMap();
    Intl.DurationFormat = function (locales, options) {
      var df = new DF(locales, options);
      args.set(df, [locales, options && JSON.parse(JSON.stringify(options))]);
      return df;
    };
    Intl.DurationFormat.prototype = proto;
    for (const [name, f] of [['format', format], ['formatToParts', formatToParts]]) {
      proto[name] = function (d) {
        var a = args.get(this);
        var out;
        // V8 rejects some valid durations (precision-exact-mathematical-values.js).
        try {
          out = f.call(this, d);
        } catch (e) {
          out = name === 'format' ? '' : [];
        }
        if (a && typeof d === 'object') {
          var record = JSON.parse(JSON.stringify(d)); // -0 becomes 0, as ToIntegerIfIntegral makes it
          // The harness implements the spec for "en" only; another locale keeps V8's result.
          var expected = a[0] !== 'en' ? out
            : name === 'format' ? formatDurationFormatPattern(this, record) : partitionDurationFormatPattern(this, record);
          __record(a[0], a[1], name, record, JSON.parse(JSON.stringify(expected)));
        }
        return out;
      };
    }
  })();`, context);
  try {
    vm.runInContext(readFileSync(join(root, file), 'utf8'), context, { filename: file });
  } catch (e) {
    failed++;
    console.error(`${file}: ${e.message}`);
  }
}
const json = JSON.stringify(cases).replace(/\},\{"locales"/g, '},\n{"locales"');
writeFileSync(new URL('./duration-format-cases.js', import.meta.url), `// Generated by host/duration-format-golden.mjs.\nvar DURATION_CASES = ${json};\n`);
console.log(`${cases.length} cases from ${files.length} files, ${failed} errors`);
